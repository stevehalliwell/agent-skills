const home = resolve(fileURLToPath(new URL('..', import.meta.url)));
const roots = [];
async function temporary() { const path = await mkdtemp(join(tmpdir(), 'gd-context-')); roots.push(path); return path; }
test.after(async () => { for (const root of roots) await rm(root, { recursive: true, force: true }); });
function git(root, args) {
  const result = spawnSync('git', ['-C', root, '-c', 'user.name=Concept Test', '-c', 'user.email=concept@example.invalid', ...args], { encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr); return result.stdout.trim();
}
function cli(root, args) {
  const result = spawnSync(process.execPath, [join(home, 'scripts/workbench.mjs'), ...args, '--project', root, '--json'], { encoding: 'utf8' });
  return { status: result.status, output: JSON.parse(result.stdout) };
}

test('setup requests mode, creates/binds one brief, preserves source and guards navigation', async () => {
  const root = await temporary();
  await assert.rejects(planSetup(root), { code: 'CONCEPT_MODE_REQUIRED' });
  assert.deepEqual(await readdir(root), []);
  for (const concept of ['../outside.md', 'tools/private.md', 'game-design/nouns/concept.md', 'AGENTS.md']) await assert.rejects(planSetup(root, { concept, mode: 'game-explorer' }), { code: 'CONCEPT_PATH_INVALID' });
  await mkdir(join(root, 'notes'));
  const original = '---\ntags: [rough]\n---\n# Existing concept\n\n## Player story\nI watch rivals react to a surprise.\n';
  await writeFile(join(root, 'notes/Original concept.md'), original);
  await writeFile(join(root, 'README.md'), '# Existing README\nKeep this text.\n');
  const options = { concept: 'notes/Original concept.md', mode: 'game-design' };
  const plan = await planSetup(root, options);
  assert.deepEqual(plan.candidate_sources, []);
  assert.equal(plan.concept.commit_required, true);
  await applySetup(root, plan.plan_id, options);
  const current = await readFile(join(root, options.concept), 'utf8');
  assert.ok(current.startsWith('---\ntags: [rough]\n---\nWorking mode: game-design\n'));
  assert.ok(current.endsWith(original.slice(original.indexOf('# Existing'))));
  assert.equal((await projectContext(root)).metadata.path, options.concept);
  assert.equal((await planSetup(root)).files.length, 0);
  const readme = await readFile(join(root, 'README.md'), 'utf8');
  assert.ok(readme.includes('Keep this text.'));
  assert.ok(readme.indexOf('Concept and working mode') < readme.indexOf('Keep this text.'), 'New navigation must be near README start.');
  assert.ok(readme.includes('(notes/Original%20concept.md)'));
  assert.equal(await readFile(join(root, options.concept), 'utf8'), current);
  const switchPlan = await planSetup(root, { mode: 'game-explorer' });
  await writeFile(join(root, options.concept), current + '\nNew user thought.\n');
  await assert.rejects(applySetup(root, switchPlan.plan_id, { mode: 'game-explorer' }), { code: 'APPROVAL_REQUIRED' });
  const freshSwitch = await planSetup(root, { mode: 'game-explorer' });
  await applySetup(root, freshSwitch.plan_id, { mode: 'game-explorer' });
  assert.ok((await readFile(join(root, options.concept), 'utf8')).includes('New user thought.'));
  await writeFile(join(root, 'README.md'), readme.replace('Concept and working mode', 'User changed navigation'));
  const conflict = await planSetup(root);
  assert.ok(conflict.conflicts.includes('Locally edited README.md concept link'));
  await assert.rejects(applySetup(root, conflict.plan_id, {}), { code: 'SETUP_CONFLICT' });
});

test('mode header is explicit, preserves body/metadata, and cannot be overridden per review', async () => {
  const root = await temporary();
  const text = '# Concept\r\n\r\nExample Working mode: game-design\r\nWorking mode: game-design\r\n\r\n## Story\r\nWorking mode: game-explorer\r\n';
  const bom = '\uFEFF# Concept\nWorking mode: game-design\n## Story\nKeep.\n';
  assert.ok(withMode(Buffer.from(bom), 'game-explorer').toString('utf8').startsWith('\uFEFF# Concept'));
  const next = withMode(Buffer.from(text), 'game-explorer').toString('utf8');
  assert.ok(next.includes('Example Working mode: game-design'));
  assert.equal(next.split('## Story')[1], text.split('## Story')[1]);
  assert.equal(describeConcept(root, 'concept.md', Buffer.from(next)).mode, 'game-explorer');
  const fenced = '# Concept\n```text\nWorking mode: nonsense\n## not a real section\n```\nWorking mode: game-design\n## Story\n';
  assert.equal(describeConcept(root, 'concept.md', Buffer.from(fenced)).mode, 'game-design');
  assert.throws(() => withMode(Buffer.from('Working mode: nonsense\n'), 'game-design'), { code: 'CONCEPT_MODE_INVALID' });
  assert.throws(() => withMode(Buffer.from('Working mode: game-design\nWorking mode: game-explorer\n'), 'game-design'), { code: 'CONCEPT_MODE_INVALID' });
  assert.throws(() => withMode(Buffer.from([255]), 'game-design'), { code: 'CONCEPT_ENCODING_INVALID' });
  assert.equal(cli(root, ['context', '--mode', 'game-design']).output.errors[0].code, 'ARGUMENT_INVALID');
  const options = { concept: 'README.md', mode: 'game-explorer' };
  const plan = await planSetup(root, options); await applySetup(root, plan.plan_id, options);
  assert.equal((await planSetup(root)).files.length, 0);
  assert.equal((await projectContext(root)).metadata.mode, 'game-explorer');
  assert.equal(cli(root, ['snapshot', '--output', join(root, 'README.md')]).output.errors[0].code, 'OUTPUT_SOURCE_CONFLICT');
  await writeFile(join(root, 'README.md'), (await readFile(join(root, 'README.md'), 'utf8')).replace('Working mode: game-explorer', 'Working mode: nonsense'));
  const invalid = cli(root, ['validate']);
  assert.equal(invalid.status, 1);
  assert.ok(invalid.output.data.diagnostics.some(item => item.code === 'CONCEPT_MODE_INVALID'));
  assert.equal(cli(root, ['query', 'skill-atoms']).output.errors[0].code, 'CONCEPT_MODE_INVALID');
});

test('Git concept revisions, drift citations, draft labels, and mode changes retain history', async () => {
  const parent = await temporary(); git(parent, ['init', '-q']);
  const root = join(parent, 'game space-é');
  await cp(join(home, 'examples/crate-puzzle'), root, { recursive: true, filter: path => !['tools', '.attendant', 'game-design-results', 'AGENTS.md'].includes(basename(path)) });
  const path = 'game-design/concept.md';
  const original = '# Game concept\nWorking mode: game-design\n\n## Intended experience\nChaotic playful rivalry.\n';
  await writeFile(join(root, path), original);
  git(parent, ['add', '.']); git(parent, ['commit', '-qm', 'Initial concept']);
  const commit = git(parent, ['rev-parse', 'HEAD']);
  const draft = original.replace('Chaotic playful rivalry.', 'Predictable solitary mastery.');
  await writeFile(join(root, path), draft);
  const read = cli(root, ['context', '--intent-ref', commit]);
  assert.equal(read.status, 0);
  assert.equal(read.output.data.revision.status, 'working_draft');
  assert.equal(read.output.data.mode, 'game-design');
  assert.equal(read.output.data.comparison.text, original);
  assert.equal(cli(root, ['context', '--intent-ref', 'HEAD']).output.errors[0].code, 'CONCEPT_REVISION_INVALID');
  const baseline = (await snapshot(root, [], { intentRef: commit })).metadata;
  assert.ok(!JSON.stringify(baseline).includes('Chaotic playful rivalry.'));
  const source = { path, section: 'Intended experience', revision: commit };
  const finding = { code: 'intent.drift', origin: 'agent', kind: 'conflicting_claims', severity: 'info', records: [], sources: [source], reason: 'Current stated direction differs from original concept; comparison is not play evidence.', suggested_investigation: 'Decide whether to revise design or adopt changed goal.', intent_relation: 'possible_goal_drift' };
  const input = { scope: ['Original/current intent'], findings: [finding], coverage: { status: 'partial' } };
  const saved = await saveReport(root, 'mda', input, baseline);
  const report = (await showReport(root, saved.run_id)).report;
  assert.equal(report.project_context.comparison.commit, commit);
  assert.equal(report.project_context.revision.status, 'working_draft');
  assert.equal((await showReport(root, saved.run_id)).matches_current_source, true);
  const mismatched = structuredClone(input); mismatched.findings[0].sources[0].revision = '0'.repeat(40);
  await assert.rejects(saveReport(root, 'mda', mismatched, baseline), { code: 'SOURCE_NOT_CAPTURED' });
  const unsupported = structuredClone(input); unsupported.findings[0].intent_relation = 'proven_fun';
  await assert.rejects(saveReport(root, 'mda', unsupported, baseline), { code: 'REPORT_INVALID' });
  for (const intent_relation of ['supports', 'contradicts']) await saveReport(root, 'mda', { ...input, findings: [{ ...finding, intent_relation }] }, baseline);
  assert.equal(git(parent, ['rev-parse', 'HEAD']), commit, 'Read-only context/review must not commit draft.');
  await writeFile(join(root, path), withMode(Buffer.from(draft), 'game-explorer'));
  assert.ok((await readFile(join(root, path), 'utf8')).includes('Predictable solitary mastery.'));
  assert.equal((await showReport(root, saved.run_id)).matches_current_source, false);
  await assert.rejects(saveReport(root, 'mda', input, baseline), { code: 'SOURCE_CHANGED' });
  git(parent, ['add', '.']); git(parent, ['commit', '-qm', 'Explicit mode and goal revision']);
  const before = (await snapshot(root)).metadata.fingerprint;
  await writeFile(join(parent, 'unrelated.txt'), 'Unrelated work.'); git(parent, ['add', 'unrelated.txt']); git(parent, ['commit', '-qm', 'Unrelated change']);
  assert.equal((await snapshot(root)).metadata.fingerprint, before);
  await rename(join(root, path), join(root, 'game-design/brief.md'));
  await mkdir(join(root, 'tools/game-design-workbench'), { recursive: true });
  await writeFile(join(root, 'tools/game-design-workbench/manifest.json'), JSON.stringify({ concept_path: 'game-design/brief.md' }));
  const renamed = await projectContext(root, { intentRef: commit, intentPath: path, includeText: true });
  assert.equal(renamed.metadata.comparison.text, original);
  const copy = await temporary(); await cp(root, copy, { recursive: true });
  const historical = await showReport(copy, saved.run_id);
  assert.equal(historical.matches_current_source, false);
  assert.ok(historical.comparison_unavailable);
  assert.equal(git(parent, ['show', `${commit}:game space-é/${path}`]), original.trim());
});
