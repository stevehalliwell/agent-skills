#!/usr/bin/env node
/** Run local smoke tests for the packaged question-research scripts. */
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { mkdtemp, mkdir, readFile, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const run = promisify(execFile);
const here = path.dirname(fileURLToPath(import.meta.url));
const temp = await mkdtemp(path.join(os.tmpdir(), "question-research-"));
const discovery = path.join(temp, "discovery");
const output = path.join(temp, "output");
await mkdir(path.join(discovery, "D-001"), { recursive: true });
await mkdir(path.join(discovery, "D-002"), { recursive: true });
await writeFile(path.join(discovery, "D-001", "source-candidates.csv"), "url,title,source_type,evidence_label,why_retain\nhttps://example.com/a?utm_source=x,First,official documentation,primary,Primary test evidence\n");
await writeFile(path.join(discovery, "D-002", "source-candidates.csv"), "url,title,source_type,evidence_label,why_retain\nhttps://example.com/a,Second,community forum,community-report,Counterpoint test evidence\n");
const node = process.execPath;
const call = async (script, ...args) => run(node, [path.join(here, script), ...args]);
await call("normalise-sources.mjs", "--input-dir", discovery, "--output-dir", output);
const index = await readFile(path.join(output, "source-index.csv"), "utf8");
const observations = await readFile(path.join(output, "source-observations.csv"), "utf8");
assert.match(index, /SRC-0001/);
assert.match(index, /2/);
assert.match(observations, /D-001:2/);
await call("prepare-capture-queue.mjs", "--index", path.join(output, "source-index.csv"), "--output", path.join(output, "capture-queue.csv"));
const reviewed = path.join(output, "capture-queue-reviewed.csv");
const queue = await readFile(path.join(output, "capture-queue.csv"), "utf8");
await writeFile(reviewed, queue.replace("initial_status", "proposed_status").replace("review-needed", "crawl4ai-candidate"));
await call("prepare-follow-up-batch.mjs", "--queue", reviewed, "--output", path.join(output, "crawl4ai.csv"));
assert.match(await readFile(path.join(output, "crawl4ai.csv"), "utf8"), /https:\/\/example.com\/a/);
await mkdir(path.join(temp, "captures", "CQ-0001"), { recursive: true });
await writeFile(path.join(temp, "captures", "CQ-0001", "page.md"), "# Captured source\n");
const captureRecords = path.join(temp, "capture-records.csv");
await writeFile(captureRecords, "queue_id,status,method,artifact_path,captured_at,detail\nCQ-0001,captured,crawl4ai,../captures/CQ-0001/page.md,2026-01-01T00:00:00Z,Fixture capture\n");
const lineage = path.join(output, "source-capture-lineage.csv");
await call("build-source-capture-lineage.mjs", "--index", path.join(output, "source-index.csv"), "--queue", reviewed, "--capture-records", captureRecords, "--output", lineage);
assert.match(await readFile(lineage, "utf8"), /captured/);
const sourceMap = path.join(temp, "source-map.md");
await call("build-source-map.mjs", "--index", path.join(output, "source-index.csv"), "--queue", reviewed, "--lineage", lineage, "--output", sourceMap);
assert.match(await readFile(sourceMap, "utf8"), /Primary test evidence/);
const register = path.join(temp, "research-register.md");
await writeFile(register, `---\nquestion_id: QR-001\nquestion: Does the example work?\noutcome: evidence-dossier\nstatus: review\ncreated_at: 2026-01-01T00:00:00Z\nupdated_at: 2026-01-01T00:00:00Z\n---\n\n# Does the example work?\n\n## Intent and boundary\n\n## First blush\n\n## Discovery batches\n\n## Source lineage\n\n- **Authoritative source map:** [source map](source-map.md)\n\n## Evidence matrix\n\n## Conflicts and gaps\n\n## Synthesis\n\n## Validation\n`);
await call("update-research-register.mjs", "--register", register, "--lineage", lineage);
assert.match(await readFile(register, "utf8"), /question-research:source-capture-status:start/);
await call("validate-research-register.mjs", "--register", register);
console.log(JSON.stringify({ status: "passed", temp }, null, 2));
